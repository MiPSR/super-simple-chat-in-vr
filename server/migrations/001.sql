PRAGMA journal_mode=WAL;
PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, name TEXT NOT NULL DEFAULT '', enabled INTEGER NOT NULL DEFAULT 1,
 world_slots INTEGER NOT NULL DEFAULT 4, avatar_slots INTEGER NOT NULL DEFAULT 8,
 world_bytes INTEGER NOT NULL DEFAULT 1000000000, avatar_bytes INTEGER NOT NULL DEFAULT 100000000,
 preferences TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS sessions (hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS assets (
 id TEXT PRIMARY KEY, owner TEXT NOT NULL REFERENCES users(id), kind TEXT NOT NULL CHECK(kind IN ('world','avatar')),
 name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', version TEXT NOT NULL, enabled INTEGER NOT NULL DEFAULT 1,
 created INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS asset_versions (
 hash TEXT PRIMARY KEY, manifest TEXT NOT NULL, bytes INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS assets_version ON assets(version);
CREATE TABLE IF NOT EXISTS blocks (
 owner TEXT NOT NULL REFERENCES users(id), target TEXT NOT NULL REFERENCES users(id), flags INTEGER NOT NULL,
 PRIMARY KEY(owner,target)
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
PRAGMA user_version=1;
